export const getDeploymentTheme = (): ThemeDefinition => {
  const envTheme = getThemeFromEnv();
  if (!envTheme) {
    return pixelTheme;
  }

  return {
    ...pixelTheme,
    modes: Object.fromEntries(
      Object.entries(pixelTheme.modes).map(([mode, definition]) => [
        mode,
        {
          ...definition,
          colors: mode === 'dark' ? definition.colors : { ...definition.colors, ...envTheme },
        },
      ]),
    ),
  };
};
